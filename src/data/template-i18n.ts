/** Look up a translated template field. Falls back to English, then returns undefined. */
export function getTemplateI18n(templateId: string, field: "name" | "desc", lang: string): string | undefined {
  const entry = TEMPLATE_I18N[templateId];
  if (!entry) return undefined;
  const map = entry[field];
  const base = lang.split("-")[0].toLowerCase();
  return map[base] ?? map.en;
}
